"""
ADAPT — Assignment Pydantic Schemas
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field

from app.schemas.question import QuestionGeneratedItem, QuestionResponse


class AssignmentMarkConfig(BaseModel):
    marks: int = Field(..., ge=1, le=50, description="Marks per question")
    count: int = Field(..., ge=1, le=20, description="Number of questions at this mark level")


class AssignmentGenerateRequest(BaseModel):
    title: Optional[str] = Field(None, description="Assignment title (auto-generated by LLM if empty)")
    description: Optional[str] = None
    units: List[int] = Field(default_factory=list, description="Target units to cover")
    cos: List[str] = Field(default_factory=list, description="Target COs")
    lo_codes: List[str] = Field(default_factory=list, description="Target LO codes")
    bloom_levels: List[str] = Field(default_factory=list, description="Target cognitive levels")
    difficulty: str = Field("MEDIUM", description="EASY | MEDIUM | HARD | MIXED")
    total_marks: Optional[int] = Field(None, ge=1, le=200, description="Total assignment marks (auto-calculated from question_counts if provided)")
    num_questions: Optional[int] = Field(None, ge=1, le=50, description="Total number of questions")
    question_counts: Dict[str, int] = Field(
        default_factory=dict,
        description="Marks → count mapping, e.g. {'2': 5, '5': 2, '10': 1}"
    )
    mark_configs: List[AssignmentMarkConfig] = Field(default_factory=list, description="Marks × count configs (alternative format)")
    question_types: List[str] = Field(default_factory=list)

    @property
    def question_counts_int(self) -> Dict[int, int]:
        """Convert question_counts string keys to int keys, merging mark_configs if present."""
        counts: Dict[int, int] = {}
        if self.question_counts:
            for k, v in self.question_counts.items():
                if v > 0:
                    counts[int(k)] = counts.get(int(k), 0) + int(v)
        elif self.mark_configs:
            for mc in self.mark_configs:
                if mc.count > 0:
                    counts[mc.marks] = counts.get(mc.marks, 0) + mc.count
        return counts

    @property
    def calculated_total_marks(self) -> int:
        counts = self.question_counts_int
        if counts:
            return sum(marks * count for marks, count in counts.items())
        return self.total_marks or 20

    @property
    def calculated_total_questions(self) -> int:
        counts = self.question_counts_int
        if counts:
            return sum(counts.values())
        return self.num_questions or 4


class AssignmentGenerationSchema(BaseModel):
    """Structured LLM output schema for assignment generation."""
    title: str = Field(..., description="A concise, creative, academic assignment title reflecting the generated question topics and units")
    description: Optional[str] = Field(None, description="Brief summary of what this assignment covers")
    questions: List[QuestionGeneratedItem] = Field(default_factory=list)


class AssignmentQuestionItem(BaseModel):
    id: UUID
    sequence_order: int
    marks: int
    question: QuestionResponse


class AssignmentResponse(BaseModel):
    id: UUID
    subject_id: UUID
    generation_run_id: Optional[UUID] = None
    title: str
    description: Optional[str] = None
    total_marks: int
    config: Dict[str, Any] = {}
    status: str
    version: int
    validation_report: Dict[str, Any] = {}
    approved_by: Optional[UUID] = None
    approved_at: Optional[datetime] = None
    created_at: datetime
    questions: List[AssignmentQuestionItem] = []

    model_config = {"from_attributes": True}


class AssignmentUpdate(BaseModel):
    title: Optional[str] = None
    description: Optional[str] = None
